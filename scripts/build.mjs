// Dependency-free build: stamps manifest.json from src/config/branding.js
// (single source of truth for naming) and packages dist/ + a CWS-ready zip.
//
//   node scripts/build.mjs            stamp manifest, copy to dist/
//   node scripts/build.mjs --release  same, but uses the release name
//                                     (no "(dev)" suffix) and zips dist/
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const release = process.argv.includes("--release");

// branding.js is a classic script that assigns globalThis.EXT_BRAND.
const brandingSource = readFileSync(join(root, "src/config/branding.js"), "utf8");
new Function(brandingSource)();
const BRAND = globalThis.EXT_BRAND;

const manifestPath = join(root, "manifest.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
manifest.name = release ? BRAND.storeName : BRAND.manifestName;
// Toolbar/extensions-menu name stays short regardless of the store name.
manifest.short_name = BRAND.name;
manifest.version = BRAND.version;
manifest.description = BRAND.description;

// Chrome silently treats an unsupported default_locale as unspecified and
// then refuses to load the extension ("Localization used, but default_locale
// wasn't specified"). es_MX is NOT supported — es / es_419 are the options.
// https://developer.chrome.com/docs/extensions/reference/api/i18n#locales
const CHROME_LOCALES = new Set([
  "ar", "am", "bg", "bn", "ca", "cs", "da", "de", "el", "en", "en_AU",
  "en_GB", "en_US", "es", "es_419", "et", "fa", "fi", "fil", "fr", "gu",
  "he", "hi", "hr", "hu", "id", "it", "ja", "kn", "ko", "lt", "lv", "ml",
  "mr", "ms", "nl", "no", "pl", "pt_BR", "pt_PT", "ro", "ru", "sk", "sl",
  "sr", "sv", "sw", "ta", "te", "th", "tr", "uk", "vi", "zh_CN", "zh_TW"
]);
if (manifest.default_locale) {
  if (!CHROME_LOCALES.has(manifest.default_locale)) {
    console.error(
      `FATAL: default_locale "${manifest.default_locale}" is not a Chrome-supported extension locale.`
    );
    process.exit(1);
  }
  if (!existsSync(join(root, "_locales", manifest.default_locale, "messages.json"))) {
    console.error(
      `FATAL: _locales/${manifest.default_locale}/messages.json missing for default_locale.`
    );
    process.exit(1);
  }
}

writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
console.log(
  `manifest.json stamped: "${manifest.name}" v${manifest.version}` +
    (manifest.default_locale ? ` (default_locale ${manifest.default_locale} ✓)` : "")
);

// Generate src/config/locale-data.js — a JS mirror of _locales so the injected
// UI can localize WITHOUT depending on Chrome's chrome.i18n message resolution
// (which has proven unreliable per browser/OS locale config). _locales stays
// the single source of truth; this file is generated, never hand-edited.
const LOCALES = ["es_419", "en"];
const bundle = {};
for (const loc of LOCALES) {
  const raw = JSON.parse(
    readFileSync(join(root, "_locales", loc, "messages.json"), "utf8")
  );
  bundle[loc] = Object.fromEntries(
    Object.entries(raw).map(([k, v]) => [k, v.message])
  );
}
writeFileSync(
  join(root, "src/config/locale-data.js"),
  "// AUTO-GENERATED by scripts/build.mjs from _locales/. Do not edit.\n" +
    '"use strict";\n' +
    "globalThis.MST_MESSAGES = Object.freeze(" +
    JSON.stringify(bundle, null, 2) +
    ");\n"
);
console.log(`locale-data.js generated (${LOCALES.join(", ")})`);

const dist = join(root, "dist");
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
cpSync(manifestPath, join(dist, "manifest.json"));
cpSync(join(root, "src"), join(dist, "src"), { recursive: true });
cpSync(join(root, "_locales"), join(dist, "_locales"), { recursive: true });
console.log("dist/ ready (load unpacked from repo root or dist/)");

if (release) {
  // The QA override (storage "mst:proOverride") is for e2e only; strip it
  // from the store build so it can't be flipped from DevTools for free PRO.
  const gatePath = join(dist, "src/pro/gate.js");
  const gateSrc = readFileSync(gatePath, "utf8");
  const stripped = gateSrc.replace(
    "override = stored[OVERRIDE_KEY] === true;",
    "override = false; // QA override stripped in release builds"
  );
  if (stripped === gateSrc) {
    console.error("FATAL: could not strip the QA override from gate.js");
    process.exit(1);
  }
  writeFileSync(gatePath, stripped);
  console.log("release: QA override stripped from gate.js");

  const zipPath = join(root, `${BRAND.name.toLowerCase().replaceAll(" ", "-")}-${BRAND.version}.zip`);
  rmSync(zipPath, { force: true });
  try {
    execFileSync("zip", ["-r", zipPath, "."], { cwd: dist });
    console.log(`packed ${zipPath}`);
  } catch {
    try {
      // zip CLI missing — Python stdlib fallback.
      execFileSync("python3", ["-m", "zipfile", "-c", zipPath, "."], { cwd: dist });
      console.log(`packed ${zipPath} (python zipfile)`);
    } catch {
      console.error("neither `zip` nor python3 available — zip dist/ manually for CWS upload.");
      process.exitCode = 1;
    }
  }
}

if (!existsSync(join(root, "src/assets/icons/icon128.png"))) {
  console.warn("warning: icons missing — run `npm run icons`");
}
